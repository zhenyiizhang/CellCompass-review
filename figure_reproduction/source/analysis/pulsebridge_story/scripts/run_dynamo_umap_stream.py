from pathlib import Path

os.environ.setdefault("MPLCONFIGDIR", "/tmp/cellcompass_dynamo_matplotlib")
os.environ.setdefault("NUMBA_CACHE_DIR", "/tmp/cellcompass_dynamo_numba")
