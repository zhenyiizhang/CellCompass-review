#!/usr/bin/env python3
"""Assemble EMT CellCompass panels into one publication-style figure.

The input panels are generated by plot_emt_cellcompass_main_panels.py.  This
script keeps the source panels as SVG groups, prefixes Matplotlib SVG IDs to
avoid collisions, and exports a combined SVG plus PDF/PNG previews when
rsvg-convert is available.
"""

from __future__ import annotations

import base64
import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from xml.etree import ElementTree as ET


ROOT = Path(__file__).resolve().parents[3]
PANEL_DIR = ROOT / "emt" / "figures" / "emt_cellcompass_main_panels"
OUT_STEM = PANEL_DIR / "figure_emt_cellcompass_publication_full"


@dataclass(frozen=True)
class PanelSpec:
    letter: str
    filename: str
    x: float
    y: float
    w: float


def parse_viewbox(path: Path) -> tuple[float, float]:
    root = ET.parse(path).getroot()
    viewbox = root.get("viewBox")
    if not viewbox:
        width = root.get("width", "").replace("pt", "")
        height = root.get("height", "").replace("pt", "")
        return float(width), float(height)
    parts = [float(x) for x in viewbox.split()]
    return parts[2], parts[3]


def prefix_svg_ids(svg: str, prefix: str) -> str:
    ids = set(re.findall(r'id="([^"]+)"', svg))
    if not ids:
        return svg
    for old in sorted(ids, key=len, reverse=True):
        new = f"{prefix}__{old}"
        svg = re.sub(rf'id="{re.escape(old)}"', f'id="{new}"', svg)
        svg = re.sub(rf'url\(\#{re.escape(old)}\)', f'url(#{new})', svg)
        svg = re.sub(rf'href="\#{re.escape(old)}"', f'href="#{new}"', svg)
        svg = re.sub(rf'xlink:href="\#{re.escape(old)}"', f'xlink:href="#{new}"', svg)
    return svg


def inner_svg(path: Path, prefix: str) -> str:
    text = path.read_text(encoding="utf-8")
    text = prefix_svg_ids(text, prefix)
    svg_match = re.search(r"<svg\b[^>]*>", text)
    if not svg_match:
        raise ValueError(f"Could not find SVG root: {path}")
    start = svg_match.end() - 1
    end = text.rfind("</svg>")
    if start < 0 or end < 0:
        raise ValueError(f"Could not parse SVG body: {path}")
    return text[start + 1 : end]


def image_tag_as_fallback(path: Path, x: float, y: float, w: float, h: float) -> str:
    """Optional fallback for viewers that dislike nested Matplotlib SVGs."""

    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f'<image x="{x:.3f}" y="{y:.3f}" width="{w:.3f}" height="{h:.3f}" href="data:image/svg+xml;base64,{data}"/>'


def panel_group(spec: PanelSpec, idx: int) -> tuple[str, float]:
    path = PANEL_DIR / spec.filename
    src_w, src_h = parse_viewbox(path)
    scale = spec.w / src_w
    h = src_h * scale
    body = inner_svg(path, f"p{idx}_{spec.letter}")
    group = [
        f'<g transform="translate({spec.x:.3f},{spec.y:.3f}) scale({scale:.6f})">',
        body,
        "</g>",
        f'<text x="{spec.x - 18:.3f}" y="{spec.y + 21:.3f}" '
        'font-family="Arial" font-size="28" font-weight="700" fill="#101828">'
        f"{spec.letter}</text>",
    ]
    return "\n".join(group), h


def build_svg() -> Path:
    margin = 34.0
    gutter = 28.0
    canvas_w = 1100.0
    col_w = (canvas_w - 2 * margin - gutter) / 2
    full_w = canvas_w - 2 * margin

    y = 34.0
    specs: list[PanelSpec] = []

    specs.append(PanelSpec("a", "panel01_human_cellcompass_emt_loop.svg", margin, y, full_w))
    y += parse_viewbox(PANEL_DIR / specs[-1].filename)[1] * full_w / parse_viewbox(PANEL_DIR / specs[-1].filename)[0] + 24

    row_y = y
    specs.append(PanelSpec("b", "panel02_condition_route_atlas.svg", margin, row_y, col_w))
    specs.append(PanelSpec("c", "panel03_endpoint_validation_scatter.svg", margin + col_w + gutter, row_y, col_w))
    row_h = max(
        parse_viewbox(PANEL_DIR / specs[-2].filename)[1] * col_w / parse_viewbox(PANEL_DIR / specs[-2].filename)[0],
        parse_viewbox(PANEL_DIR / specs[-1].filename)[1] * col_w / parse_viewbox(PANEL_DIR / specs[-1].filename)[0],
    )
    y += row_h + 26

    specs.append(PanelSpec("d", "panel02b_observed_generated_emt_core_timecourses.svg", margin, y, full_w))
    y += parse_viewbox(PANEL_DIR / specs[-1].filename)[1] * full_w / parse_viewbox(PANEL_DIR / specs[-1].filename)[0] + 26

    row_y = y
    specs.append(PanelSpec("e", "panel04_mechanism_fingerprint_cards.svg", margin, row_y, col_w))
    specs.append(PanelSpec("f", "panel05_three_layer_mechanism.svg", margin + col_w + gutter, row_y, col_w))
    row_h = max(
        parse_viewbox(PANEL_DIR / specs[-2].filename)[1] * col_w / parse_viewbox(PANEL_DIR / specs[-2].filename)[0],
        parse_viewbox(PANEL_DIR / specs[-1].filename)[1] * col_w / parse_viewbox(PANEL_DIR / specs[-1].filename)[0],
    )
    y += row_h + 26

    specs.append(PanelSpec("g", "panel06_representative_mechanism_timing.svg", margin, y, full_w))
    y += parse_viewbox(PANEL_DIR / specs[-1].filename)[1] * full_w / parse_viewbox(PANEL_DIR / specs[-1].filename)[0] + 36

    groups = []
    for idx, spec in enumerate(specs):
        group, _ = panel_group(spec, idx)
        groups.append(group)

    canvas_h = y
    svg = f'''<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     width="{canvas_w:.0f}pt" height="{canvas_h:.0f}pt" viewBox="0 0 {canvas_w:.3f} {canvas_h:.3f}">
  <rect x="0" y="0" width="{canvas_w:.3f}" height="{canvas_h:.3f}" fill="white"/>
  <text x="{margin:.3f}" y="25" font-family="Arial" font-size="18" font-weight="700" fill="#101828">
    CellCompass reconstructs context-aware EMT dynamics across cancer-cell states
  </text>
  {"".join(groups)}
</svg>
'''
    out_svg = OUT_STEM.with_suffix(".svg")
    out_svg.write_text(svg, encoding="utf-8")
    return out_svg


def export_with_rsvg(svg_path: Path) -> None:
    converter = shutil.which("rsvg-convert")
    if not converter:
        print("rsvg-convert not found; wrote SVG only.")
        return
    subprocess.run([converter, "-f", "pdf", "-o", str(OUT_STEM.with_suffix(".pdf")), str(svg_path)], check=True)
    subprocess.run([converter, "--width", "2400", "-f", "png", "-o", str(OUT_STEM.with_suffix(".png")), str(svg_path)], check=True)


def main() -> None:
    svg = build_svg()
    export_with_rsvg(svg)
    print(f"Wrote publication figure: {OUT_STEM}.svg")


if __name__ == "__main__":
    main()
